/** Shown to Dutch members in place of the English ratings line the server stores in the transcript. */
export function displayRatingsText(text: string, lang: Lang): string {
  if (lang === "en") return text;
  return text.replace(en.ratingsTurnPrefix, nl.ratingsTurnPrefix).replace(/\(skipped\)/g, `(${nl.skipped})`);
}
