// Generates lib/aiwd/seed.ts from prototype/src/seed.js (evaluated with a fake window) so the
// data is byte-faithful to the artifact. Run from web/: node scripts/gen-seed.mjs
import fs from "node:fs";
import path from "node:path";
import vm from "node:vm";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const src = path.join(here, "..", "..", "prototype", "src", "seed.js");
const out = path.join(here, "..", "lib", "aiwd", "seed.ts");

const ctx = { window: {} };
vm.runInNewContext(fs.readFileSync(src, "utf8"), ctx, { filename: src });
const SEED = JSON.parse(JSON.stringify(ctx.window.SEED));
if (!Array.isArray(SEED) || !SEED.length) throw new Error("seed.js did not define window.SEED");

const body = `/* seed.ts: 16 fictional member profiles. GENERATED by scripts/gen-seed.mjs from
 * prototype/src/seed.js. Do not edit by hand; edit the prototype and re-run the script. */
import type { Profile } from "./types";

export const SEED: Profile[] = ${JSON.stringify(SEED, null, 2)};
`;
fs.writeFileSync(out, body);
console.log(`wrote ${path.relative(process.cwd(), out)}: ${SEED.length} profiles`);
